import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export async function generateRules(root) {
  const securityDir = join(root, 'rules/security');
  const names = (await readdir(securityDir)).filter(name => name.endsWith('.yaml')).sort();
  const security = await Promise.all(names.map(name => readFile(join(securityDir, name), 'utf8')));
  const conflicts = await readFile(join(root, 'rules/conflicts.yaml'), 'utf8');
  const knownNames = await readFile(join(root, 'rules/known-names.txt'), 'utf8');
  return '// Generated by scripts/gen-rules.mjs. Do not edit.\n'
    + `export const securityYaml = ${JSON.stringify(security)};\n`
    + `export const conflictsYaml = ${JSON.stringify(conflicts)};\n`
    + `export const knownNamesText = ${JSON.stringify(knownNames)};\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  await writeFile(join(root, 'src/scan/rules.generated.ts'), await generateRules(root));
}
